# ============================================================
# 🤖 AI Priority Scoring
# ระบบจัดลำดับความสำคัญของ Ticket
# ============================================================


def calculate_priority_score(
    nlp_category=None,
    severity=None,
    severity_score=None,
    duplicate_status=None
):
    """
    คำนวณคะแนนความเร่งด่วนของ Ticket

    คะแนนเต็ม 100 คะแนน

    ข้อมูลที่ใช้:
    1. ประเภทปัญหาจาก NLP
    2. Severity ความรุนแรง
    3. ผล Duplicate Detection
    """

    # ========================================================
    # 1. เริ่มต้นคะแนน
    # ========================================================

    score = 0


    # ========================================================
    # 2. คะแนนจากประเภทปัญหา
    # ========================================================

    category_scores = {
        "น้ำท่วม": 30,
        "กิ่งไม้/ต้นไม้": 30,
        "ประปา": 25,
        "ถนนชำรุด": 25,
        "ไฟสาธารณะ": 25,
        "ขยะ": 20,
        "อื่นๆ": 20
    }

    score += category_scores.get(
        nlp_category,
        20
    )


    # ========================================================
    # 3. คะแนนจาก Severity
    # ========================================================

    if severity == "สูง":

        score += 35

    elif severity == "ปานกลาง":

        score += 20

    elif severity == "ต่ำ":

        score += 5


    # ========================================================
    # 4. คะแนนจาก Duplicate Detection
    # ========================================================

    if duplicate_status == "อาจซ้ำสูง":

        score += 10


    # ========================================================
    # 6. จำกัดคะแนนสูงสุดไม่เกิน 100
    # ========================================================

    score = min(score, 100)


    # ========================================================
    # 7. แปลงคะแนนเป็นระดับความเร่งด่วน
    # หากพบความรุนแรงระดับสูง หรือคะแนนรวม >= 55 จัดเป็น "เร่งด่วน" ทันที
    # ========================================================

    if severity == "สูง" or score >= 55:

        priority = "เร่งด่วน"

    elif score >= 35:

        priority = "ปานกลาง"

    else:

        priority = "ปกติ"


    # ========================================================
    # 8. ส่งผลลัพธ์กลับ
    # ========================================================

    return {
        "score": score,
        "priority": priority
    }


