# ============================================================
# 🤖 AI Severity Assessment
# ประเมินระดับความรุนแรงจากข้อความประชาชน
# ============================================================

def predict_text_severity(text):
    """
    ประเมินระดับความรุนแรงจากข้อความ

    ผลลัพธ์:
    - ต่ำ
    - ปานกลาง
    - สูง
    """

    # ========================================================
    # ตรวจสอบข้อความ
    # ========================================================

    if not text:
        return {
            "severity": "ไม่ทราบ",
            "score": 0,
            "matched_keywords": []
        }

    text = text.lower().strip()

    # ========================================================
    # คำที่สื่อถึงความรุนแรงระดับสูง
    # ========================================================

    high_keywords = [
        "รถผ่านไม่ได้",
        "รถสัญจรไม่ได้",
        "สัญจรไม่ได้",
        "ผ่านไม่ได้",
        "รถสัญจรลำบากมากที่สุด",
        "รถสัญจรลำบากมากทีสุด",
        "รถสัญจรลำบากมาก",
        "สัญจรลำบากมากที่สุด",
        "สัญจรลำบากมากทีสุด",
        "สัญจรลำบากมาก",
        "รถผ่านลำบากมากที่สุด",
        "รถผ่านลำบากมาก",
        "ผ่านลำบากมาก",
        "ลำบากมากที่สุด",
        "ลำบากมากทีสุด",
        "ลำบากที่สุด",
        "ลำบากมาก",
        "พังหนัก",
        "เสียหายหนัก",
        "อันตราย",
        "อันตรายมาก",
        "เสี่ยงต่อชีวิต",
        "เกิดอุบัติเหตุ",
        "ถนนขาด",
        "กีดขวางทางทั้งหมด",
        "ท่วมหนัก",
        "น้ำท่วมสูง",
        "หนักมาก",
        "รั่วหนักมาก",
        "รั่วหนัก",
        "ท่อแตก",
        "น้ำรั่วหนัก",
        "น้ำไหลทะลัก",
        "ไหลไม่หยุด",
        "เดือดร้อนหนัก",
        "ฉุกเฉิน",
        "เร่งด่วน",
        "วิกฤต"
    ]

    # ========================================================
    # คำที่สื่อถึงความรุนแรงระดับปานกลาง
    # ========================================================

    medium_keywords = [
        "หลายจุด",
        "รถผ่านลำบาก",
        "สัญจรลำบาก",
        "เสียหายมาก",
        "ชำรุดมาก",
        "เริ่มอันตราย",
        "กีดขวางทาง",
        "น้ำท่วม",
        "น้ำขัง",
        "ขยะล้น",
        "ต้นไม้ล้ม",
        "รั่ว",
        "น้ำรั่ว",
        "รั่วไหล",
        "ไหลรั่ว",
        "ท่อรั่ว"
    ]

    # ========================================================
    # คำที่สื่อถึงความรุนแรงระดับต่ำ
    # ========================================================

    low_keywords = [
        "เล็ก",
        "เล็กน้อย",
        "นิดหน่อย",
        "ไม่มาก",
        "เล็ก ๆ",
        "เล็กๆ",
        "เสียหายนิดหน่อย",
        "ชำรุดเล็กน้อย"
    ]

    # ========================================================
    # ค้นหาคำที่ตรงกับข้อความ
    # ========================================================

    high_matches = [
        word
        for word in high_keywords
        if word in text
    ]

    medium_matches = [
        word
        for word in medium_keywords
        if word in text
    ]

    low_matches = [
        word
        for word in low_keywords
        if word in text
    ]

    # ========================================================
    # ถ้าพบคำระดับสูง ให้ถือว่าเป็นระดับสูงทันที
    # ========================================================

    if high_matches:
        return {
            "severity": "สูง",
            "score": 3,
            "matched_keywords": high_matches
        }

    # ========================================================
    # ถ้าพบคำระดับปานกลาง
    # ========================================================

    if medium_matches:
        return {
            "severity": "ปานกลาง",
            "score": 2,
            "matched_keywords": medium_matches
        }

    # ========================================================
    # ถ้าพบคำระดับต่ำ
    # ========================================================

    if low_matches:
        return {
            "severity": "ต่ำ",
            "score": 1,
            "matched_keywords": low_matches
        }

    # ========================================================
    # ถ้าไม่พบคำบอกระดับความรุนแรง
    # ========================================================

    return {
        "severity": "ไม่ทราบ",
        "score": 0,
        "matched_keywords": []
    }


