# ============================================================

import cv2


# ============================================================
# ฟังก์ชันหลักสำหรับวิเคราะห์คุณภาพรูปภาพ
# ============================================================

def predict_image_quality(image_path):

    # --------------------------------------------------------
    # 1. อ่านรูปภาพ
    # --------------------------------------------------------

    image = cv2.imread(image_path)

    # ถ้าอ่านรูปไม่ได้
    if image is None:
        return {
            "quality": "อ่านรูปไม่ได้",
            "score": 0.0,
            "sharpness": 0.0,
            "brightness": 0.0
        }


    # --------------------------------------------------------
    # 2. ตรวจสอบขนาดรูปภาพ
    # --------------------------------------------------------

    height, width = image.shape[:2]


    # --------------------------------------------------------
    # 3. วิเคราะห์ความคมชัด
    #
    # ใช้ Laplacian Variance
    # ถ้าค่าสูง = ภาพมีรายละเอียด/ขอบภาพมาก
    # ถ้าค่าต่ำ = ภาพมีแนวโน้มเบลอ
    # --------------------------------------------------------

    gray = cv2.cvtColor(
        image,
        cv2.COLOR_BGR2GRAY
    )

    laplacian_variance = cv2.Laplacian(
        gray,
        cv2.CV_64F
    ).var()


    # --------------------------------------------------------
    # 4. แปลงค่าความคมชัดเป็นคะแนน 0-100
    #
    # ค่านี้เป็นเกณฑ์เริ่มต้นสำหรับโปรเจกต์
    # สามารถปรับภายหลังจากการทดสอบภาพจริง
    # --------------------------------------------------------

    sharpness_score = min(
        laplacian_variance / 10,
        100
    )


    # --------------------------------------------------------
    # 5. วิเคราะห์ความสว่าง
    #
    # ค่าเฉลี่ยประมาณ 0-255
    # --------------------------------------------------------

    brightness_value = gray.mean()


    # --------------------------------------------------------
    # 6. แปลงความสว่างเป็นคะแนน
    #
    # ช่วงประมาณ 50-200 ถือว่าใช้งานได้ดี
    # --------------------------------------------------------

    if brightness_value < 50:

        brightness_score = (
            brightness_value / 50
        ) * 100

    elif brightness_value > 200:

        brightness_score = (
            (255 - brightness_value) / 55
        ) * 100

    else:

        brightness_score = 100


    brightness_score = max(
        0,
        min(brightness_score, 100)
    )


    # --------------------------------------------------------
    # 7. ตรวจสอบขนาดภาพ
    # --------------------------------------------------------

    if width >= 640 and height >= 480:

        size_score = 100

    elif width >= 320 and height >= 240:

        size_score = 70

    else:

        size_score = 40


    # --------------------------------------------------------
    # 8. คำนวณคะแนนรวม
    #
    # ความคมชัด = 60%
    # ความสว่าง = 30%
    # ขนาดภาพ = 10%
    # --------------------------------------------------------

    quality_score = (
        (sharpness_score * 0.60)
        +
        (brightness_score * 0.30)
        +
        (size_score * 0.10)
    )


    quality_score = round(
        quality_score,
        2
    )


    # --------------------------------------------------------
    # 9. แปลคะแนนเป็นระดับคุณภาพ
    # --------------------------------------------------------

    if quality_score >= 70:

        quality = "ชัดเจน"

    elif quality_score >= 40:

        quality = "ปานกลาง"

    else:

        quality = "ไม่ชัดเจน"


    # ========================================================
    # ส่งผลลัพธ์กลับ
    # ========================================================

    return {
        "quality": quality,
        "score": quality_score,
        "sharpness": round(
            sharpness_score,
            2
        ),
        "brightness": round(
            brightness_score,
            2
        ),
        "width": width,
        "height": height
    }


# ============================================================
# จบ AI Image Quality Analysis
# ============================================================

# ============================================================
# 📷 Image Quality Validation
# ตรวจสอบว่ารูปภาพสามารถนำไปวิเคราะห์ต่อได้หรือไม่
# ============================================================

def validate_image_quality(result):

    score = result.get("score", 0)
    sharpness = result.get("sharpness", 0)
    brightness = result.get("brightness", 0)

    # --------------------------------------------------------
    # กำหนดเกณฑ์เบื้องต้น
    # --------------------------------------------------------

    if score < 60:
        return {
            "passed": False,
            "reason": "คุณภาพภาพโดยรวมต่ำเกินไป"
        }

    if sharpness < 30:
        return {
            "passed": False,
            "reason": "รูปภาพไม่ชัดหรือเบลอ"
        }

    if brightness < 20:
        return {
            "passed": False,
            "reason": "รูปภาพมืดเกินไป"
        }

    return {
        "passed": True,
        "reason": "รูปภาพมีคุณภาพเพียงพอสำหรับการวิเคราะห์"
    }

