# ============================================================
# 🤖 NLP Category
# วิเคราะห์ข้อความร้องเรียนเพื่อหาประเภทปัญหา
# ============================================================

def predict_nlp_category(text):
    """
    วิเคราะห์ข้อความร้องเรียน
    และจำแนกประเภทปัญหา

    ผลลัพธ์:
    - category
    - confidence
    """

    if not text:
        return {
            "category": "อื่นๆ",
            "confidence": 0.0
        }

    text = text.lower().strip()

    # ============================================================
    # 🤖 ปรับปรุง NLP Keyword
    # ให้คำสำคัญเฉพาะเจาะจงมีน้ำหนักมากกว่าคำทั่วไป
    # ============================================================

    keywords = {
        "ถนนชำรุด": [
            "ถนนพัง",
            "ถนนชำรุด",
            "ทางพัง",
            "พื้นถนน",
            "ผิวถนน",
            "หลุม",
            "หลุมบนถนน",
            "หลุมถนน",
            "ลาดยาง"
        ],
        "น้ำท่วม": [
            "น้ำท่วม",
            "ท่วม",
            "น้ำขัง",
            "น้ำระบาย",
            "ระบายน้ำ",
            "คลอง",
            "น้ำเสีย"
        ],
        "ขยะ": [
            "ขยะ",
            "ถังขยะ",
            "กองขยะ",
            "ขยะเต็ม",
            "ขยะล้น",
            "สิ่งปฏิกูล",
            "เก็บขยะ"
        ],
        "กิ่งไม้/ต้นไม้": [
            "ต้นไม้",
            "กิ่งไม้",
            "ต้นไม้ล้ม",
            "กิ่งไม้หัก",
            "กิ่งไม้ขวาง",
            "ต้นไม้พัง"
        ],
        "ไฟสาธารณะ": [
            "ไฟหน้าถนน",
            "ไฟถนน",
            "ไฟส่องสว่าง",
            "ไฟสาธารณะ",
            "ไฟไม่ติด",
            "ไฟดับ",
            "เสาไฟ",
            "หลอดไฟ"
        ],
        "ประปา": [
            "ประปา",
            "ท่อประปา",
            "น้ำประปา",
            "ท่อน้ำ",
            "น้ำรั่ว",
            "ท่อแตก",
            "รั่วไหล",
            "ไหลรั่ว",
            "ท่อรั่ว",
            "ก๊อกน้ำ",
            "มิเตอร์น้ำ",
            "ประปาแตก"
        ],
        "อื่นๆ": [
            "ร้องเรียน",
            "ปัญหา",
            "เดือดร้อน"
        ]
    }

    # ============================================================
    # จบการปรับปรุง NLP Keyword
    # ============================================================

    # ========================================================
    # นับคะแนนจากคำสำคัญ
    # ========================================================

    scores = {}

    for category, words in keywords.items():
        score = 0

        for word in words:
            if word in text:
                score += 1

        scores[category] = score

    # ========================================================
    # หา Category ที่มีคะแนนสูงสุด
    # ========================================================

    best_category = max(scores, key=scores.get)
    best_score = scores[best_category]

    # ========================================================
    # ถ้าไม่พบคำสำคัญ
    # ========================================================

    if best_score == 0:
        return {
            "category": "อื่นๆ",
            "confidence": 0.30
        }

    # ========================================================
    # คำนวณ Confidence
    # ========================================================

    total_score = sum(scores.values())
    confidence = best_score / total_score if total_score else 0.0

    return {
        "category": best_category,
        "confidence": confidence
    }


